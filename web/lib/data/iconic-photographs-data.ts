// ─── Iconic American Photographs ──────────────────────────────────────────────
// Curated set of landmark American photographs with caption + context.
//
// This file is intentionally decoupled from the gallery image manifest
// (gallery-assets.ts) so the content can exist before the image binaries are
// sourced. As each image is obtained from a free / public-domain source
// (Wikimedia Commons, NASA, Library of Congress, National Archives, DoD, etc.)
// it gets dropped into web/IMAGES/... and its repo-relative path recorded in
// `imagePath` here, then wired into the gallery and the relevant section page.
//
// `rights` records the practical sourcing status:
//   "public-domain" — US gov / NASA / pre-1929 / federal work; free to use.
//   "loc"           — available via Library of Congress (verify PD per item).
//   "needs-license" — copyrighted press/film/sports/product image; user supplies.

export type PhotoRights = "public-domain" | "loc" | "needs-license";

export type PhotoSection =
  | "economy"
  | "military"
  | "culture"
  | "innovation"
  | "quality-of-life"
  | "constitution";

export interface IconicPhoto {
  /** Stable kebab-case id, also used as the React key. */
  id: string;
  /** Display title. */
  title: string;
  /** Year or year range as shown in the caption. */
  year: string;
  /** Short caption (~one line). */
  caption: string;
  /** 1–2 sentence context: what it is and why it matters. */
  description: string;
  /** Gallery category this belongs to (matches GALLERY_CATEGORIES where possible). */
  category: string;
  /** Site section(s) the image should surface on. */
  section: PhotoSection;
  /** Where it was taken / its subject's location. */
  location: string;
  /** Sourcing status for the image-acquisition pass. */
  rights: PhotoRights;
  /** Best free source to pull the image from (filled in for the image pass). */
  source: string;
  /** Repo-relative path under web/IMAGES once the file is added. */
  imagePath?: string;
}

