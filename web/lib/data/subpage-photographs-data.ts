// ─── Subpage Photographs ──────────────────────────────────────────────────────
// Curated photographs tied to specific sub-pages (Universities, Global
// Leadership, Innovation, Culture, Military, Constitution). Same model as
// iconic-photographs-data.ts but with a `subpage` slug so each image can be
// surfaced on its specific sub-page in addition to the main gallery.
//
// Content-first: entries exist before images are sourced. `rights` records the
// sourcing status; `imagePath` is filled once the file lands under web/IMAGES.

export type PhotoRights = "public-domain" | "loc" | "needs-license";

export interface SubpagePhoto {
  id: string;
  title: string;
  year: string;
  /** One-sentence context: what it is and why it matters. */
  blurb: string;
  /** Gallery category (matches GALLERY_CATEGORIES where possible). */
  category: string;
  /** Main site section. */
  section: string;
  /** Sub-page slug, e.g. "ivy-league", "internet-history", "navy", "bill-of-rights". */
  subpage: string;
  rights: PhotoRights;
  source: string;
  imagePath?: string;
}

